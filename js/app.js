let currentLang = 'id';
const totalItems = 6;
const checkStates = [false, false, false, false, false, false];

/* ==========================================================
Slideshow Engine
========================================================== */
let currentSlide = 0;
let slideTimer = null;
const slideDuration = 4500;

function updateSlideUI() {
  const slides = document.querySelectorAll('.slide-item');
  const totalSlides = slides.length;
  if (!totalSlides) return;

  slides.forEach((slide, idx) => {
    if (idx === currentSlide) {
      slide.classList.add('active');
    } else {
      slide.classList.remove('active');
    }
  });

  const dots = document.querySelectorAll('#slide-indicators button');
  dots.forEach((dot, idx) => {
    if (idx === currentSlide) {
      dot.className = "h-2 rounded-full transition-all duration-300 bg-emerald-400 w-8";
    } else {
      dot.className = "h-2 rounded-full transition-all duration-300 bg-white/40 w-3 hover:bg-white/70";
    }
  });

  const counterEl = document.getElementById('slide-counter-badge');
  if (counterEl) {
    counterEl.textContent = `0${currentSlide + 1} / 0${totalSlides}`;
  }

  const captionKey = `slide_badge_${currentSlide + 1}`;
  const captionEl = document.getElementById('slide-caption-badge');
  if (captionEl && i18nData[currentLang] && i18nData[currentLang][captionKey]) {
    captionEl.textContent = i18nData[currentLang][captionKey];
  }
}

function nextSlide() {
  const totalSlides = document.querySelectorAll('.slide-item').length;
  if (!totalSlides) return;
  currentSlide = (currentSlide + 1) % totalSlides;
  updateSlideUI();
  restartSlideTimer();
}

function prevSlide() {
  const totalSlides = document.querySelectorAll('.slide-item').length;
  if (!totalSlides) return;
  currentSlide = (currentSlide - 1 + totalSlides) % totalSlides;
  updateSlideUI();
  restartSlideTimer();
}

function goToSlide(idx) {
  currentSlide = idx;
  updateSlideUI();
  restartSlideTimer();
}

function startSlideTimer() {
  if (slideTimer) clearInterval(slideTimer);
  slideTimer = setInterval(nextSlide, slideDuration);
}

function restartSlideTimer() {
  startSlideTimer();
}

/* ==========================================================
Scroll-Reveal & Reading Bar
========================================================== */
function initScrollReveal() {
  const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add('revealed');
      }
    });
  }, {
    threshold: 0.1,
    rootMargin: '0px 0px -40px 0px'
  });

  document.querySelectorAll('.reveal-on-scroll').forEach(el => observer.observe(el));

  window.addEventListener('scroll', () => {
    const winScroll = document.documentElement.scrollTop || document.body.scrollTop;
    const height = document.documentElement.scrollHeight - document.documentElement.clientHeight;
    const scrolled = (winScroll / height) * 100;
    const bar = document.getElementById('scroll-indicator');
    if (bar) bar.style.width = `${scrolled}%`;
  }, { passive: true });
}

/* ==========================================================
Audio & Feedback
========================================================== */
function playClickTone(isSuccess = false) {
  try {
    const AudioContext = window.AudioContext || window.webkitAudioContext;
    if (!AudioContext) return;
    const ctx = new AudioContext();
    const osc = ctx.createOscillator();
    const gain = ctx.createGain();

    osc.connect(gain);
    gain.connect(ctx.destination);

    if (isSuccess) {
      osc.type = 'triangle';
      osc.frequency.setValueAtTime(523.25, ctx.currentTime);
      osc.frequency.exponentialRampToValueAtTime(659.25, ctx.currentTime + 0.1);
      osc.frequency.exponentialRampToValueAtTime(783.99, ctx.currentTime + 0.2);
      gain.gain.setValueAtTime(0.15, ctx.currentTime);
      gain.gain.exponentialRampToValueAtTime(0.001, ctx.currentTime + 0.35);
      osc.start();
      osc.stop(ctx.currentTime + 0.35);
    } else {
      osc.type = 'sine';
      osc.frequency.setValueAtTime(440, ctx.currentTime);
      gain.gain.setValueAtTime(0.08, ctx.currentTime);
      gain.gain.exponentialRampToValueAtTime(0.001, ctx.currentTime + 0.08);
      osc.start();
      osc.stop(ctx.currentTime + 0.08);
    }
  } catch (e) {}
}

/* ==========================================================
Multi-language Switcher
========================================================== */
function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('trail_guide_lang', lang);

  const btnId = document.getElementById('lang-btn-id');
  const btnEn = document.getElementById('lang-btn-en');

  if (lang === 'id') {
    if (btnId) btnId.className = "px-3.5 py-1.5 rounded-full text-xs font-bold transition-all duration-200 flex items-center gap-1.5 bg-emerald-500 text-forest-950 shadow-sm";
    if (btnEn) btnEn.className = "px-3.5 py-1.5 rounded-full text-xs font-bold transition-all duration-200 flex items-center gap-1.5 text-stone-300 hover:text-white";
    document.documentElement.lang = 'id';
  } else {
    if (btnEn) btnEn.className = "px-3.5 py-1.5 rounded-full text-xs font-bold transition-all duration-200 flex items-center gap-1.5 bg-emerald-500 text-forest-950 shadow-sm";
    if (btnId) btnId.className = "px-3.5 py-1.5 rounded-full text-xs font-bold transition-all duration-200 flex items-center gap-1.5 text-stone-300 hover:text-white";
    document.documentElement.lang = 'en';
  }

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (i18nData[lang] && i18nData[lang][key]) {
      el.innerHTML = i18nData[lang][key];
    }
  });

  updateProgressUI(false);
  updateSlideUI();
  if (window.lucide) {
    lucide.createIcons();
  }
}

/* ==========================================================
Interactive Checklist Engine (State Based)
========================================================== */
function updateItemVisual(index, isChecked) {
  const box = document.getElementById(`box-check-${index}`);
  const icon = document.getElementById(`icon-check-${index}`);
  const card = document.getElementById(`card-check-${index}`);

  if (box && icon && card) {
    if (isChecked) {
      box.style.backgroundColor = '#1B4332';
      box.style.borderColor = '#1B4332';
      box.style.transform = 'scale(1.08)';
      icon.style.opacity = '1';
      card.style.borderColor = '#94C6AF';
      card.style.backgroundColor = '#F2F8F5'; // Latar mint lembut natural
    } else {
      box.style.backgroundColor = '#ffffff';
      box.style.borderColor = '#d6d3d1';
      box.style.transform = 'scale(1)';
      icon.style.opacity = '0';
      card.style.borderColor = '#e7e5e4';
      card.style.backgroundColor = '#ffffff';
    }
  }
}

function getCheckedCount() {
  return checkStates.filter(Boolean).length;
}

function toggleCheck(index) {
  const arrayIdx = index - 1;
  checkStates[arrayIdx] = !checkStates[arrayIdx];
  const newState = checkStates[arrayIdx];

  localStorage.setItem(`trail_item_${index}`, newState ? 'true' : 'false');
  updateItemVisual(index, newState);

  const count = getCheckedCount();
  const isComplete = count === totalItems;

  playClickTone(isComplete);
  if (navigator.vibrate) {
    navigator.vibrate(isComplete ? [60, 40, 60] : 30);
  }

  updateProgressUI(true);
}

function resetChecklist() {
  for (let i = 1; i <= totalItems; i++) {
    checkStates[i - 1] = false;
    localStorage.removeItem(`trail_item_${i}`);
    updateItemVisual(i, false);
  }
  updateProgressUI(false);
}

function triggerConfetti() {
  if (typeof confetti === 'function') {
    confetti({
      particleCount: 70,
      spread: 75,
      origin: { y: 0.6 },
      colors: ['#2D6A4F', '#10B981', '#06B6D4', '#F59E0B']
    });
  }
}

function updateProgressUI(allowCelebration = false) {
  const count = getCheckedCount();
  const percent = Math.round((count / totalItems) * 100);

  const bar = document.getElementById('checklist-progress');
  if (bar) bar.style.width = `${percent}%`;

  const countEl = document.getElementById('checklist-count');
  if (countEl) {
    countEl.textContent = currentLang === 'id'
      ? `${count}/${totalItems} Siap`
      : `${count}/${totalItems} Ready`;
  }

  const banner = document.getElementById('ready-congrats');
  if (banner) {
    if (count === totalItems) {
      if (banner.classList.contains('hidden') && allowCelebration) {
        triggerConfetti();
      }
      banner.classList.remove('hidden');
    } else {
      banner.classList.add('hidden');
    }
  }

  const stickyText = document.getElementById('sticky-progress-text');
  const stickyLabel = document.getElementById('sticky-label');
  const stickyIconBox = document.getElementById('sticky-icon-box');

  if (stickyText && stickyLabel && stickyIconBox) {
    stickyLabel.textContent = i18nData[currentLang].sticky_title;
    if (count === totalItems) {
      stickyText.textContent = i18nData[currentLang].sticky_done;
      stickyIconBox.className = "w-8 h-8 rounded-xl bg-emerald-500/20 text-emerald-400 flex items-center justify-center shrink-0";
    } else {
      stickyText.textContent = currentLang === 'id'
        ? `${count} dari ${totalItems} tercentang`
        : `${count} of ${totalItems} completed`;
      stickyIconBox.className = "w-8 h-8 rounded-xl bg-amber-500/20 text-amber-400 flex items-center justify-center shrink-0 animate-pulse";
    }
  }
}

/* ==========================================================
Inisialisasi Keseluruhan Aplikasi
========================================================== */
function initApp() {
  if (window.lucide) {
    lucide.createIcons();
  }
  startSlideTimer();
  initScrollReveal();

  const heroSlideshowEl = document.getElementById('hero-slideshow');
  if (heroSlideshowEl) {
    let touchStartX = 0;
    let touchEndX = 0;
    heroSlideshowEl.addEventListener('touchstart', e => {
      touchStartX = e.changedTouches[0].screenX;
    }, { passive: true });
    heroSlideshowEl.addEventListener('touchend', e => {
      touchEndX = e.changedTouches[0].screenX;
      if (touchEndX < touchStartX - 45) nextSlide();
      if (touchEndX > touchStartX + 45) prevSlide();
    }, { passive: true });

    heroSlideshowEl.addEventListener('mouseenter', () => clearInterval(slideTimer));
    heroSlideshowEl.addEventListener('mouseleave', startSlideTimer);
  }

  // Restore checklist dari localStorage saat web pertama dibuka
  for (let i = 1; i <= totalItems; i++) {
    const saved = localStorage.getItem(`trail_item_${i}`);
    const isChecked = saved === 'true';
    checkStates[i - 1] = isChecked;
    updateItemVisual(i, isChecked);
  }
  updateProgressUI(false);

  const savedLang = localStorage.getItem('trail_guide_lang') || 'id';
  setLanguage(savedLang);
}

